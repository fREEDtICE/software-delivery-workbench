"""End-to-end acceptance for the AWS EC2 / Alibaba ECS cloud runtime.

The verifier is written against the HELIOS-3 acceptance contract, not the
internal module layout: it drives the administrator CLI through real
subprocesses, injects cloud faults through the fake provider APIs and only
asserts behaviour an independent acceptor can observe (phases, cloud identity,
task receipts, reclamation, credential boundaries). The AWS Signature V4 check
uses the official published documentation test vector.
"""

import argparse
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import tempfile
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cloud_runtime import bootstrap  # noqa: E402
from cloud_runtime.fakes import FakeCloud  # noqa: E402
from cloud_runtime.providers import (  # noqa: E402
    FAKE_ALIYUN_SECRET_KEY, FAKE_AWS_SECRET_KEY, aws_signed_headers,
)

ADMIN_TOKEN_ENV = "HELIOS_ADMIN_TOKEN"
ADMIN_TOKEN = "helios-admin-token-" + "a" * 24
PROVIDER_FACTS = {
    "aws": {"region": "us-east-1", "image": "ami-0helioslinux", "type": "t3.micro",
            "subnet": "subnet-helios", "sg": ["sg-helios-a"], "profile": "helios-runtime-role",
            "ak_env": "HELIOS_AWS_AK", "sk_env": "HELIOS_AWS_SK"},
    "aliyun": {"region": "cn-hangzhou", "image": "aliyun_helios_linux", "type": "ecs.t6-c1m1.large",
               "subnet": "vsw-helios", "sg": ["sg-helios-b"], "profile": "helios-runtime-ram-role",
               "ak_env": "HELIOS_ALIYUN_AK", "sk_env": "HELIOS_ALIYUN_SK"},
}


class Recorder:
    def __init__(self):
        self.checks = []

    def check(self, name, condition, *, expected=None, observed=None):
        self.checks.append({
            "name": name, "passed": bool(condition),
            **({"expected": expected, "observed": observed} if expected is not None or observed is not None else {}),
        })
        if not condition:
            raise AssertionError(f"{name}: expected {expected!r}, observed {observed!r}")

    def expect_raises(self, name, fn, reason):
        try:
            fn()
        except Exception as error:  # noqa: BLE001 - acceptance records the failure shape
            observed = getattr(error, "reason", type(error).__name__)
            self.check(name, observed == reason, expected=reason, observed=observed)
            return error
        self.check(name, False, expected=reason, observed="no error")


class Cli:
    def __init__(self, state_dir, endpoints):
        self.state_dir = state_dir
        self.endpoints = endpoints
        self.env = {**os.environ, ADMIN_TOKEN_ENV: ADMIN_TOKEN,
                    "PYTHONPATH": str(ROOT), "PYTHONIOENCODING": "utf-8"}

    def run(self, *args, expect=0):
        cmd = [sys.executable, "-m", "cloud_runtime.cli", "--state-dir", self.state_dir, *args]
        result = subprocess.run(cmd, cwd=ROOT, env=self.env, text=True, capture_output=True, timeout=120)
        payload = json.loads(result.stdout) if result.stdout.strip() else {}
        if result.returncode != expect:
            raise AssertionError(f"cli {' '.join(args)} rc={result.returncode}\n{result.stdout}\n{result.stderr}")
        return payload

    def configure(self, provider):
        facts = PROVIDER_FACTS[provider]
        return self.run(
            "configure", "--workspace-id", "ws-helios",
            "--workspace-url", self.endpoints["workspace"], "--admin-token-env", ADMIN_TOKEN_ENV,
            "--gateway-url", self.endpoints["workspace"] + "/gateway",
            "--provider", provider, "--mode", "fake", "--region", facts["region"],
            "--endpoint", self.endpoints[provider], "--image-id", facts["image"],
            "--instance-type", facts["type"], "--subnet-id", facts["subnet"],
            "--sg", facts["sg"][0], "--profile", facts["profile"],
            "--access-key-env", facts["ak_env"], "--secret-key-env", facts["sk_env"],
            "--binding", "agent-legacy=rt-legacy-local",
        )

    def provision(self, name, provider, **kwargs):
        args = ["provision", "--name", name, "--provider", provider]
        for key, value in kwargs.items():
            args += ["--" + key.replace("_", "-"), str(value)]
        return self.run(*args)

    def state(self, name):
        return self.run("status", "--name", name)


def verify_aws_sigv4_official_vector(recorder):
    # Vectors from the AWS Signature Version 4 test suite as shipped in
    # botocore tests/unit/auth/aws4_testsuite (get-vanilla and
    # get-vanilla-with-session-token). Expected Authorization headers are
    # AWS-published values, not generated by this implementation.
    common = dict(method="GET", url="https://example.amazonaws.com/", query={},
                  headers={"X-Amz-Date": "20150830T123600Z"}, body=b"",
                  access_key="AKIDEXAMPLE",
                  secret_key="wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY",
                  region="us-east-1", service="service", amz_date="20150830T123600Z")
    vanilla = aws_signed_headers(**common)["Authorization"]
    recorder.check(
        "aws-sigv4-official-vector",
        vanilla == "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20150830/us-east-1/service/aws4_request, "
                   "SignedHeaders=host;x-amz-date, "
                   "Signature=5fa00fa31553b73ebf1942676e86291e8372ff2a2260956d9b8aae1d763fbf31",
        observed=vanilla)
    with_token = aws_signed_headers(
        session_token="6e86291e8372ff2a2260956d9b8aae1d763fbf315fa00fa31553b73ebf194267",
        **common)["Authorization"]
    recorder.check(
        "aws-sigv4-session-token-vector",
        with_token == "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20150830/us-east-1/service/aws4_request, "
                      "SignedHeaders=host;x-amz-date;x-amz-security-token, "
                      "Signature=07ec1639c89043aa0e3e2de82b96708f198cceab042d4a97044c66dd9f74e7f8",
        observed=with_token)


def verify_tampered_signature_rejected(recorder, cloud, provider):
    # A forged request must be rejected at the wire before any instance changes.
    from cloud_runtime.providers import build_provider
    cfg = {"mode": "fake", "region": PROVIDER_FACTS[provider]["region"],
           "endpoint": cloud.endpoints()[provider],
           "access_key_env": "X", "secret_key_env": "Y"}
    adapter = build_provider(provider, cfg)
    if provider == "aws":
        adapter.secret_key = FAKE_AWS_SECRET_KEY + "tampered"
        recorder.expect_raises(provider + "-tampered-signature", adapter.authorize,
                               "authorization_failed")
    else:
        adapter.secret_key = FAKE_ALIYUN_SECRET_KEY + "tampered"
        recorder.expect_raises(provider + "-tampered-signature", adapter.authorize,
                               "authorization_failed")


def verify_lease_enforcement(recorder, cloud):
    # The formal daemon entry only accepts the short-lived lease for this work.
    def register(lease):
        request = urllib.request.Request(
            cloud.endpoints()["workspace"] + "/api/daemon/register",
            data=json.dumps({"daemon_id": "d", "runtimes": [
                {"name": "x", "type": "cloud-aws", "runtime_mode": "cloud",
                 "version": "0", "status": "online"}]}).encode(),
            headers={"Authorization": "Bearer " + lease, "Content-Type": "application/json"}, method="POST")
        try:
            with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(request, timeout=10) as response:
                return response.status, json.load(response)
        except urllib.error.HTTPError as error:
            return error.code, json.load(error)

    status, body = register("never-issued-lease")
    recorder.check("unknown-lease-denied", status == 403 and body["error"]["code"] == "lease_required",
                   expected=(403, "lease_required"), observed=(status, body.get("error")))

    import hashlib
    expired_lease = "expired-" + "e" * 40
    cloud.workspace.activations["expired-runtime"] = {
        "id": "act-expired", "status": "pending", "registered_runtime_id": None,
        "runtime_name": "expired-runtime",
        "lease_sha256": hashlib.sha256(expired_lease.encode()).hexdigest(),
        "expires_at": int(time.time()) - 60, "capabilities": []}
    status, body = register(expired_lease)
    recorder.check("expired-lease-denied", status == 403 and body["error"]["code"] == "lease_expired",
                   expected=(403, "lease_expired"), observed=(status, body.get("error")))


def verify_provider_happy_path(recorder, cloud, cli, provider):
    name = provider + "-main"
    state = cli.provision(name, provider, readiness_timeout=30, poll_interval=0.05)
    facts = PROVIDER_FACTS[provider]
    recorder.check(provider + "-phase-ready", state["phase"] == "ready", expected="ready",
                   observed=state["phase"])
    identity = state["identity"]
    recorder.check(provider + "-cloud-identity",
                   identity["provider"] == provider and identity["region"] == facts["region"]
                   and identity["instance_id"].startswith(("i-", "i-bp"))
                   and identity["instance_profile"] == facts["profile"],
                   observed=identity)
    recorder.check(provider + "-phases-visible",
                   [event["event"] for event in state["events"]][:3] ==
                   ["authorize_start", "authorize_passed", "network_ready"],
                   observed=[event["event"] for event in state["events"]])

    # The exact user-data stored by the cloud is fetched back and audited.
    from cloud_runtime.providers import build_provider
    adapter = build_provider(provider, {"mode": "fake", "region": facts["region"],
                                        "endpoint": cloud.endpoints()[provider],
                                        "access_key_env": "X", "secret_key_env": "Y"})
    user_data = adapter.get_user_data(state["instance_id"])
    recorder.check(provider + "-userdata-roundtrip",
                   bootstrap.embedded_files(user_data), observed="no embedded config")
    lease_doc = bootstrap.parse_lease(user_data)
    recorder.check(provider + "-lease-short-lived",
                   0 < lease_doc["expires_at"] - int(time.time()) <= 900,
                   observed=lease_doc["expires_at"] - int(time.time()))
    rendered = user_data + json.dumps(lease_doc)
    recorder.check(provider + "-no-long-lived-cloud-secret",
                   FAKE_AWS_SECRET_KEY not in rendered and FAKE_ALIYUN_SECRET_KEY not in rendered
                   and "HELIOS_AWS_SK" not in rendered and "HELIOS_ALIYUN_SK" not in rendered
                   and facts["profile"] in user_data,
                   observed="secret material present" if False else "profile-only reference")
    runtime_cfg = bootstrap.parse_runtime_config(user_data)
    recorder.check(provider + "-formal-register-entry",
                   runtime_cfg["register_path"] == "/api/daemon/register"
                   and runtime_cfg["runtime_mode"] == "cloud",
                   observed=runtime_cfg)
    if provider == "aws":
        recorder.check(provider + "-console-registration-marker",
                       "registered through /api/daemon/register" in state["console_output"],
                   observed=state["console_output"][:120])

    # Default runtime and dispatch rules.
    cli.run("set-default", "--name", name)
    decision = cli.run("dispatch-check", "--agent-id", "agent-new-1", "--new")
    recorder.check(provider + "-new-agent-goes-cloud",
                   decision["location"] == "cloud" and decision["fallback"] is False
                   and decision["instance_id"] == state["instance_id"], observed=decision)
    legacy = cli.run("dispatch-check", "--agent-id", "agent-legacy", "--existing")
    recorder.check(provider + "-existing-binding-kept",
                   legacy["location"] == "existing-binding" and legacy["runtime_id"] == "rt-legacy-local",
                   observed=legacy)

    # A task survives the originating CLI process: first call times out while
    # the cloud instance keeps executing, a fresh process resumes by task id.
    timed_out = cli.run("smoke-task", "--name", name, "--timeout", "0.02", expect=1)
    recorder.check(provider + "-task-originator-can-exit",
                   timed_out["error"]["reason"] == "provision_timeout",
                   expected="provision_timeout", observed=timed_out["error"])
    task = cli.run("smoke-task", "--name", name, "--timeout", "30")["task"]
    resumed = cli.state(name)["task"]
    recorder.check(provider + "-task-resumed-by-id",
                   resumed["task_id"] == task["task_id"] and task["status"] == "completed",
                   observed=task)
    recorder.check(provider + "-receipt-proves-execution-site",
                   task["receipt"]["instance"]["instance_id"] == state["instance_id"]
                   and task["receipt"]["result"]["answer"] == 42, observed=task["receipt"])

    # Reclamation: cloud instance and workspace registration both go away.
    cli.run("teardown", "--name", name)
    terminated = cli.state(name)
    recorder.check(provider + "-teardown-terminated",
                   terminated["phase"] == "terminated", observed=terminated["phase"])
    recorder.check(provider + "-no-active-instance",
                   cloud.active_instances(provider) == [], observed=cloud.active_instances(provider))
    audit = cli.run("audit")
    recorder.check(provider + "-audit-no-orphan", audit["orphan_count"] == 0, observed=audit)


def verify_authorization_failure_then_retry(recorder, cloud, cli, provider):
    name = provider + "-auth"

    def launches():
        return [call for call in cloud.cloud.calls
                if call["provider"] == provider and call["action"] == "instance_launched"]

    before = len(launches())
    cloud.set_auth_failure(provider, True)
    payload = cli.run("provision", "--name", name, "--provider", provider,
                      "--readiness-timeout", "5", expect=1)
    error = payload["error"]
    recorder.check(provider + "-auth-insufficient-reason",
                   error["reason"] == "authorization_failed" and bool(error.get("actionable")),
                   observed=error)
    state = cli.state(name)
    recorder.check(provider + "-auth-failure-no-instance",
                   state["phase"] == "failed" and not state.get("instance_id"), observed=state["phase"])
    recorder.check(provider + "-auth-failure-bills-nothing", len(launches()) == before,
                   expected=before, observed=len(launches()))

    cloud.set_auth_failure(provider, False)
    ready = cli.run("retry", "--name", name, "--readiness-timeout", "30", "--poll-interval", "0.05")
    recorder.check(provider + "-retry-after-auth-ready", ready["phase"] == "ready",
                   expected="ready", observed=ready["phase"])
    recorder.check(provider + "-single-billable-instance", len(launches()) - before == 1,
                   expected=1, observed=len(launches()) - before)
    cli.run("teardown", "--name", name)


def verify_provision_timeout_retry_and_cancel(recorder, cloud, cli, provider):
    def calls(action):
        return [call for call in cloud.cloud.calls
                if call["provider"] == provider and call["action"] == action]

    name = provider + "-stall"
    cloud.set_stall(provider, True)
    payload = cli.run("provision", "--name", name, "--provider", provider,
                      "--readiness-timeout", "0.6", "--poll-interval", "0.05", expect=1)
    recorder.check(provider + "-provision-timeout-reason",
                   payload["error"]["reason"] == "provision_timeout"
                   and bool(payload["error"].get("actionable")), observed=payload["error"])
    failed = cli.state(name)
    recorder.check(provider + "-timeout-keeps-instance-id",
                   failed["phase"] == "failed" and bool(failed["instance_id"]), observed=failed["phase"])
    instance_id = failed["instance_id"]

    # Cancellation while provisioning must release the half-open resource.
    cli.run("teardown", "--name", name)
    recorder.check(provider + "-cancel-reclaims-instance",
                   all(item["state"] == "terminated"
                       for item in cloud.cloud.snapshot(provider)
                       if item["instance_id"] == instance_id), observed="instance still active")
    audit = cli.run("audit")
    recorder.check(provider + "-cancel-audit-clean", audit["orphan_count"] == 0, observed=audit)
    cloud.set_stall(provider, False)

    # A second runtime proves retry reuses the same instance via the client token.
    name2 = provider + "-retry"
    launches_before = len(calls("instance_launched"))
    cloud.set_stall(provider, True)
    cli.run("provision", "--name", name2, "--provider", provider,
            "--readiness-timeout", "0.6", "--poll-interval", "0.05", expect=1)
    cloud.set_stall(provider, False)
    retried = cli.run("retry", "--name", name2, "--readiness-timeout", "30", "--poll-interval", "0.05")
    recorder.check(provider + "-retry-same-instance",
                   retried["instance_id"] == cli.state(name2)["instance_id"]
                   and retried["phase"] == "ready", observed=retried)
    launched_delta = len(calls("instance_launched")) - launches_before
    recorder.check(provider + "-resume-never-relaunches",
                   launched_delta == 1, observed={"launched_delta": launched_delta})
    cli.run("teardown", "--name", name2)


def verify_client_token_idempotency(recorder, cloud, provider):
    # Issuing the same launch twice (same ClientToken) must yield one billable
    # instance, exercising the cloud's own idempotency contract end to end.
    from cloud_runtime.providers import LaunchSpec, build_provider
    facts = PROVIDER_FACTS[provider]
    adapter = build_provider(provider, {"mode": "fake", "region": facts["region"],
                                        "endpoint": cloud.endpoints()[provider],
                                        "access_key_env": "X", "secret_key_env": "Y"})
    token = "fixed-idempotency-token-" + provider
    spec = LaunchSpec(name="dup-check", image_id=facts["image"], instance_type=facts["type"],
                      subnet_id=facts["subnet"], security_group_ids=facts["sg"],
                      user_data="#!/bin/bash\ntrue\n", profile=facts["profile"],
                      client_token=token, workspace_id="ws-helios", runtime_name="dup-check")
    before = len([c for c in cloud.cloud.calls
                  if c["provider"] == provider and c["action"] == "instance_launched"])
    first = adapter.run_instances(spec)
    second = adapter.run_instances(spec)
    after = len([c for c in cloud.cloud.calls
                 if c["provider"] == provider and c["action"] == "instance_launched"])
    recorder.check(provider + "-client-token-single-instance",
                   first.instance_id == second.instance_id and after - before == 1,
                   observed={"first": first.instance_id, "second": second.instance_id,
                             "launches": after - before})
    adapter.terminate_instance(first.instance_id)


def verify_no_silent_local_fallback(recorder, cloud, cli, provider):
    name = provider + "-fallback"
    cli.provision(name, provider, readiness_timeout=30, poll_interval=0.05)
    cli.run("set-default", "--name", name)
    cli.run("teardown", "--name", name)
    payload = cli.run("dispatch-check", "--agent-id", "agent-new-2", "--new", expect=1)
    recorder.check(provider + "-cloud-down-explicit-unavailable",
                   payload["error"]["reason"] == "runtime_unavailable"
                   and payload["error"].get("actionable"), observed=payload["error"])
    recorder.check(provider + "-never-falls-back-to-local",
                   "fallback" not in payload["error"], observed=payload["error"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=Path("evidence/cloud-runtime/e2e.json"))
    parser.add_argument("--provider", choices=["aws", "aliyun", "both"], default="both")
    args = parser.parse_args()
    providers = ["aws", "aliyun"] if args.provider == "both" else [args.provider]

    report = {"scenario": "cloud-runtime-e2e", "status": "FAIL", "python": platform.python_version(),
              "mode": "fake-cloud", "commit": os.getenv("GITHUB_SHA"),
              "run_id": os.getenv("GITHUB_RUN_ID"), "providers": providers, "checks": []}
    recorder = Recorder()
    with tempfile.TemporaryDirectory(prefix="helios-cloud-") as state_dir:
        cloud = FakeCloud(ADMIN_TOKEN)
        try:
            cli = Cli(state_dir, cloud.endpoints())
            for provider in providers:
                cli.configure(provider)
            verify_aws_sigv4_official_vector(recorder)
            verify_lease_enforcement(recorder, cloud)
            for provider in providers:
                verify_tampered_signature_rejected(recorder, cloud, provider)
                verify_client_token_idempotency(recorder, cloud, provider)
                verify_provider_happy_path(recorder, cloud, cli, provider)
                verify_authorization_failure_then_retry(recorder, cloud, cli, provider)
                verify_provision_timeout_retry_and_cancel(recorder, cloud, cli, provider)
                verify_no_silent_local_fallback(recorder, cloud, cli, provider)
        finally:
            cloud.stop()
        report["checks"] = recorder.checks
    report["status"] = "PASS" if all(check["passed"] for check in recorder.checks) else "FAIL"

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for check in recorder.checks:
        print(("PASS" if check["passed"] else "FAIL"), check["name"])
    print(f"cloud runtime e2e / {','.join(providers)} / {report['status']} "
          f"({sum(c['passed'] for c in recorder.checks)}/{len(recorder.checks)})")
    if summary := os.getenv("GITHUB_STEP_SUMMARY"):
        with open(summary, "a", encoding="utf-8") as stream:
            stream.write(f"### Cloud runtime E2E: {report['status']}\n")
            for check in recorder.checks:
                stream.write(f"- {'PASS' if check['passed'] else 'FAIL'} {check['name']}\n")
    return 0 if report["status"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
